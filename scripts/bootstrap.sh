#!/usr/bin/env bash
# Set up (or bring up to date) the shared Zephyr workspace this repo builds
# against. Safe to re-run; re-run after changing west.yml or requirements.txt.
#
# The workspace lives outside the repo so every checkout and worktree shares one
# copy of Zephyr, the HALs and the toolchain (several GB). Only the pins that
# define it (west.yml, requirements.txt) are tracked here.
#
# Requires git and uv (https://docs.astral.sh/uv/). No Homebrew: Python comes
# from uv and cmake/ninja from PyPI, so everything is native to the machine.
#
# Default location is xiao-ws/ next to the main checkout; override with XIAO_WS.
# Afterwards: source "$XIAO_WS/env.sh", then build from any checkout with
#   west build -b xiao_mg24 app
set -euo pipefail

# On Apple Silicon, a shell started from an Intel process (e.g. an x86_64 tmux)
# runs under Rosetta and would produce an Intel workspace. Re-run natively.
if [[ "$(sysctl -n sysctl.proc_translated 2>/dev/null)" == 1 ]]; then
  exec arch -arm64 /bin/bash "$0" "$@"
fi

command -v uv >/dev/null || { echo "missing: uv (https://docs.astral.sh/uv/)" >&2; exit 1; }

# Resolve via the shared .git dir so worktrees land on the same workspace as
# the main checkout.
COMMON_GIT="$(cd "$(git -C "$(dirname "$0")" rev-parse --git-common-dir)" && pwd)"
MAIN="$(dirname "$COMMON_GIT")"
REPO="$(git -C "$(dirname "$0")" rev-parse --show-toplevel)"
WS="${XIAO_WS:-$(dirname "$MAIN")/xiao-ws}"

# Matches $ZEPHYR_BASE/SDK_VERSION for the Zephyr pinned in west.yml.
ZEPHYR_SDK_VERSION=1.0.1

echo "== workspace: $WS"
mkdir -p "$WS/manifest"

echo "== python venv"
# uv's own CPython build, not whatever python3 is on PATH (conda, Homebrew,
# Intel or arm), so every machine gets the same interpreter. --seed adds pip,
# which `west packages pip` calls.
[[ -d "$WS/.venv" ]] || uv venv --quiet --seed --managed-python --python 3.12 "$WS/.venv"
# shellcheck disable=SC1091
source "$WS/.venv/bin/activate"
uv pip install --quiet -r "$REPO/requirements.txt"

echo "== west update"
cp "$REPO/west.yml" "$WS/manifest/west.yml"
[[ -d "$WS/.west" ]] || west init -l "$WS/manifest"
cd "$WS"
# Shallow, and only the allowlisted projects, to keep the download small.
west update --narrow --fetch-opt=--depth=1
west packages pip --install -- --quiet

echo "== silabs radio blob"
west blobs fetch hal_silabs

echo "== zephyr sdk $ZEPHYR_SDK_VERSION (arm only)"
SDK_DIR="$WS/zephyr-sdk-$ZEPHYR_SDK_VERSION"
if [[ "$(uname)" == Darwin ]]; then
  # The SDK's setup.sh runs `env bash` and picks its download from bash's
  # HOSTTYPE. An Intel-only bash on PATH (e.g. Intel Homebrew's) reports x86_64,
  # and there is no macOS x86_64 toolchain to download. Point `bash` at the
  # universal system one, which runs natively.
  SHIM="$WS/.bin"
  mkdir -p "$SHIM"
  ln -sf /bin/bash "$SHIM/bash"
  PATH="$SHIM:$PATH"
fi
if [[ ! -d "$SDK_DIR" ]]; then
  west sdk install --version "$ZEPHYR_SDK_VERSION" --install-dir "$SDK_DIR" -t arm-zephyr-eabi
elif [[ ! -d "$SDK_DIR/gnu/arm-zephyr-eabi" ]]; then
  # A previous run unpacked the SDK but didn't get the toolchain.
  (cd "$SDK_DIR" && ./setup.sh -t arm-zephyr-eabi)
fi

echo "== pyocd target pack"
pyocd pack install EFR32MG24

cat > "$WS/env.sh" <<EOF
# Generated by scripts/bootstrap.sh. Source before building or flashing.
source "$WS/.venv/bin/activate"
export ZEPHYR_BASE="$WS/zephyr"
export ZEPHYR_SDK_INSTALL_DIR="$SDK_DIR"
export ZEPHYR_TOOLCHAIN_VARIANT=zephyr
EOF

echo "done. next: source $WS/env.sh && west build -b xiao_mg24 app"
